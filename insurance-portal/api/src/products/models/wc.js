/**
 * Workmen's Compensation & Employer's Liability rating model (WC BRD section 8).
 * Step-for-step equivalent of products/wc/rater.js; the parity test proves identical results.
 */
const base = {
  valid: 'true', tier: "'wc'", currency: 'country.currency', sumInsured: 'round(wages, dec)', maxLocationSI: 'round(wages, dec)', employees: 'employees', period: 'period',
};

module.exports = {
  name: 'Workmen’s Compensation & Employer’s Liability',
  requiredTables: ['trades', 'categories', 'plans', 'factors', 'extensions', 'statutory', 'charges'],
  steps: [
    { set: 'dec', expr: 'country.currency_decimals' },
    { set: 'trade', expr: 'find(tables.trades, item.code == risk.trade)' },
    { error: 'TRADE_UNKNOWN', when: 'trade == null' },
    { set: 'plan', expr: 'tables.plans[risk.plan]' },
    { error: 'PLAN_UNKNOWN', when: '!plan' },
    {
      set: 'rows',
      expr: "risk.policyType == 'named'"
        + ' ? map(group(risk.employees, item.category), {category: item.key, headcount: len(item.items), annualWages: sum(item.items, num(item.gross) * 12), avgBasic: sum(item.items, num(item.basic)) / len(item.items), avgGross: sum(item.items, num(item.gross)) / len(item.items)})'
        + ' : map(filter(risk.categories, item.headcount > 0 || item.annualWages > 0), {category: item.category, headcount: item.headcount, avgBasic: item.avgBasic, avgGross: item.avgGross, annualWages: item.annualWages != null ? num(item.annualWages) : item.headcount * num(item.avgGross) * 12})',
    },
    { error: 'WORKFORCE_REQUIRED', when: 'len(rows) == 0' },
    { each: 'rows', as: 'r', steps: [{ error: 'CATEGORY_UNKNOWN', when: 'find(tables.categories, item.code == r.category) == null', field: 'r.category' }] },
    { set: 'el', expr: 'plan.el ? (risk.elLimit || plan.el) : null' },
    { error: 'EL_LIMIT_NOT_OFFERED', when: 'el && tables.factors.elLoading[el] == null' },
    {
      each: 'risk.extensions || []', as: 'code', steps: [
        { set: 'ext', expr: 'tables.extensions[code]' },
        { error: 'EXTENSION_UNKNOWN', when: '!ext', field: 'code' },
        { error: 'EXTENSION_NOT_AVAILABLE', when: 'ext && ext.plans && !includes(ext.plans, risk.plan)', field: 'code' },
      ],
    },
    { checkpoint: true },
    { set: 'employees', expr: 'sum(rows, item.headcount)' },
    { set: 'wages', expr: 'sum(rows, item.annualWages)' },
    { set: 'period', expr: 'risk.inceptionDate ? {inception: risk.inceptionDate, expiry: addDays(addMonths(risk.inceptionDate, risk.periodMonths), -1)} : undefined' },
    { when: "trade.status == 'decline'", return: { ...base, quotable: 'false', notQuotableReason: "'TRADE_DECLINED'" } },
    { when: 'employees > settings.online.maxEmployees || wages > settings.online.maxWages', return: { ...base, quotable: 'false', notQuotableReason: "'ABOVE_ONLINE_LIMIT'" } },
    { set: 'claimsFactor', expr: 'tables.factors.claims[str(min(2, risk.claims3y || 0))]' },
    { set: 's', expr: 'tables.statutory' },
    {
      each: 'rows', as: 'r', collect: 'lineRows', steps: [
        { set: 'c', expr: 'find(tables.categories, item.code == r.category)' },
        { set: 'premium', expr: 'r.annualWages * c.rate * trade.factor * claimsFactor' },
        { set: 'line', expr: 'merge(r, {rate: c.rate, medPerHead: c.medPerHead, sectionA: round(premium, dec), avgGross: round(r.avgGross, 2), avgBasic: round(r.avgBasic, 2), deathBenefitAtAvgBasic: min(s.deathMax, max(s.deathMin, r.avgBasic * s.deathMonths))})' },
        { set: 'bad', expr: 'line.headcount > 0 && line.avgGross > 0 && line.avgGross < c.minWage' },
      ],
    },
    { set: 'lines', expr: 'map(lineRows, item.line)' },
    { set: 'sectionA', expr: 'sum(lines, item.annualWages * item.rate * trade.factor * claimsFactor)' },
    { set: 'sectionB', expr: 'el ? sectionA * tables.factors.elLoading[el] : 0' },
    { set: 'sectionC', expr: 'plan.medical ? sum(lines, item.headcount * item.medPerHead) : 0' },
    {
      each: 'risk.extensions || []', as: 'code', collect: 'extLines', steps: [
        { set: 'ext', expr: 'tables.extensions[code]' },
        { set: 'amount', expr: "round(ext.method == 'loading_a' ? sectionA * ext.pct : (ext.method == 'per_head' ? employees * ext.amount : (ext.method == 'fixed' ? ext.amount : 0)), dec)" },
        { set: 'referral', expr: "!!(ext.referral || ext.method == 'referral_only')" },
      ],
    },
    { set: 'extensions', expr: 'map(extLines, {code: item.code, amount: item.amount})' },
    { set: 'extTotal', expr: 'sum(extensions, item.amount)' },
    { set: 'periodFactor', expr: 'tables.factors.period[risk.periodMonths] ?? 1' },
    { set: 'annual', expr: 'sectionA + sectionB + sectionC + extTotal' },
    { set: 'technical', expr: 'annual * periodFactor' },
    { set: 'uwLoadingPct', expr: 'num(uwTerms.loadingPct || 0)' },
    { set: 'loaded', expr: 'technical * (1 + uwLoadingPct)' },
    { set: 'discountPct', expr: 'uwTerms.discountPct != null ? num(uwTerms.discountPct) : num(risk.discountPct || 0)' },
    { set: 'discount', expr: 'loaded * discountPct' },
    { set: 'premium', expr: 'round(max(tables.charges.minPremium, loaded - discount), dec)' },
    { set: 'policyFee', expr: 'round(tables.charges.policyFee, dec)' },
    { set: 'vatRate', expr: 'num(country.vat_rate)' },
    { set: 'tax', expr: 'round((premium + policyFee) * vatRate, dec)' },
  ],
  output: {
    ...base,
    quotable: 'true',
    lines: 'lines',
    'breakdown.sectionA': 'round(sectionA, dec)',
    'breakdown.sectionB': 'round(sectionB, dec)',
    'breakdown.sectionC': 'round(sectionC, dec)',
    'breakdown.elLimit': 'el',
    'breakdown.medicalLimit': 'plan.medical ? s.medicalLimitPerEmployee : null',
    'breakdown.extensions': 'extensions',
    'breakdown.extensionsTotal': 'round(extTotal, dec)',
    'breakdown.annualPremium': 'round(annual, dec)',
    'breakdown.periodMonths': 'risk.periodMonths',
    'breakdown.periodFactor': 'periodFactor',
    'breakdown.technicalPremium': 'round(technical, dec)',
    'breakdown.uwLoadingPct': 'uwLoadingPct',
    'breakdown.uwLoading': 'round(loaded - technical, dec)',
    'breakdown.discountPct': 'discountPct',
    'breakdown.discount': 'round(discount, dec)',
    'breakdown.minimumPremiumApplied': 'loaded - discount < tables.charges.minPremium',
    'breakdown.premium': 'premium',
    'breakdown.policyFee': 'policyFee',
    'breakdown.vatRate': 'vatRate',
    'breakdown.tax': 'tax',
    'breakdown.total': 'round(premium + policyFee + tax, dec)',
    'breakdown.locationsPremium': 'round(sectionA, dec)',
    'facts.employees': 'employees',
    'facts.wages': 'wages',
    'facts.hazardClass': 'trade.hazardClass',
    'facts.tradeFactor': 'trade.factor',
    'facts.exceedsAutoLimit': '(authority.maxEmployees != null && employees > authority.maxEmployees) || (authority.maxWages != null && wages > authority.maxWages)',
    'facts.hazardOutsideAuthority': "trade.status == 'refer' || !includes(authority.hazardClasses || [1], trade.hazardClass)",
    'facts.adverseClaims': '(risk.claims3y || 0) >= 2 || risk.fatalClaim3y == true',
    'facts.hasReferralExtension': 'any(extLines, item.referral)',
    'facts.wageImplausible': 'any(lineRows, item.bad)',
    'facts.elAboveAuthority': 'el != null && authority.maxEL != null && el > authority.maxEL',
    'facts.backdatedJoiner': 'risk.backdatedJoiner == true',
    'facts.discountPct': 'num(risk.discountPct || 0)',
    'facts.discountExceedsBand': 'num(risk.discountPct || 0) > (authority.maxDiscount ?? 0)',
    'facts.sanctionsHit': '!!sanctionsHit',
    'facts.previouslyDeclined': 'risk.previouslyDeclined == true',
  },
};
