/**
 * Fire & Allied Perils rating model (Fire BRD section 8), expressed for the dynamic rating engine.
 * Step-for-step equivalent of products/fire/rater.js; the parity test proves identical results.
 */
const ASSETS = ['BLD', 'IMP', 'PLM', 'FFF', 'STK', 'OTH'];
const SI = 'sumValues(item.sumsInsured, ASSETS)';

const base = {
  valid: 'true', currency: 'country.currency', sumInsured: 'round(totalSI, dec)', maxLocationSI: 'round(maxLocationSI, dec)', tier: 'tier',
};

module.exports = {
  name: 'Fire & Allied Perils',
  requiredTables: ['occupancies', 'factors', 'extensions', 'charges'],
  constants: { ASSETS },
  exposure: { sumInsuredKeys: ASSETS },
  steps: [
    { set: 'dec', expr: 'country.currency_decimals' },
    { set: 'f', expr: 'tables.factors' },
    { set: 'charges', expr: 'tables.charges' },
    { set: 'occ', expr: 'find(tables.occupancies, item.code == risk.occupancy)' },
    { error: 'OCCUPANCY_UNKNOWN', when: 'occ == null' },
    { set: 'locations', expr: 'risk.locations ?? []' },
    { error: 'LOCATION_REQUIRED', when: 'len(locations) == 0' },
    { set: 'selectedExt', expr: 'risk.extensions ?? []' },
    { each: 'selectedExt', as: 'code', steps: [{ error: 'EXTENSION_UNKNOWN', when: '!has(tables.extensions, code)', field: 'code' }] },
    {
      each: 'locations', as: 'loc', index: 'i', steps: [
        { error: 'SUM_INSURED_REQUIRED', when: 'sumValues(loc.sumsInsured, ASSETS) <= 0', field: "'locations.' + i" },
        { error: 'OTH_ABOVE_SUBLIMIT', when: 'pos(loc.sumsInsured.OTH) > charges.othSubLimit', field: "'locations.' + i + '.OTH'" },
      ],
    },
    { checkpoint: true },
    { set: 'totalSI', expr: `sum(locations, ${SI})` },
    { set: 'maxLocationSI', expr: `max_of(locations, ${SI})` },
    { set: 'tier', expr: "maxLocationSI <= settings.tiers.tier1 ? 'tier1' : (maxLocationSI <= settings.tiers.tier2 ? 'tier2' : 'above')" },
    { when: "occ.status == 'decline'", return: { ...base, quotable: 'false', notQuotableReason: "'OCCUPANCY_DECLINED'" } },
    { when: "tier == 'above'", return: { ...base, quotable: 'false', notQuotableReason: "'ABOVE_ONLINE_LIMIT'" } },
    { set: 'claims3y', expr: 'min(2, max(0, num(risk.claims3y)))' },
    { set: 'claimsFactor', expr: "lookup(f.claims, str(claims3y), 'claims')" },
    {
      each: 'locations', as: 'loc', index: 'i', collect: 'locs', steps: [
        { set: 'si', expr: 'sumValues(loc.sumsInsured, ASSETS)' },
        { set: 'prot', expr: "loc.protection.sprinklers ? 'sprinklers' : (loc.protection.alarm ? 'alarm' : (loc.protection.extinguishers ? 'extinguishers' : 'none'))" },
        {
          set: 'applied',
          expr: "{construction: lookup(f.construction, loc.construction, 'construction'), protection: f.protection[prot], civilDefence: f.civilDefence[loc.civilDefence == false ? 'no' : 'yes'], natcat: lookup(f.natcat, loc.natcatZone || 'low', 'natcat'), claims: claimsFactor, buildingAge: lookup(f.buildingAge, loc.buildingAge, 'buildingAge'), siBand: band(f.siBands, si)}",
        },
        { set: 'basePremium', expr: 'si * occ.ratePermille / 1000' },
        { set: 'premium', expr: 'round(basePremium * applied.construction * applied.protection * applied.civilDefence * applied.natcat * applied.claims * applied.buildingAge * applied.siBand, dec)' },
      ],
    },
    { set: 'locationsPremium', expr: 'sum(locs, item.premium)' },
    {
      each: 'selectedExt', as: 'code', collect: 'extLines', steps: [
        { set: 'ext', expr: 'tables.extensions[code]' },
        { fail: 'UNKNOWN_EXTENSION_METHOD', when: "!includes(['loading', 'rate_on_groups', 'rate_on_total', 'rate_on_input', 'referral_only'], ext.method)" },
        { set: 'available', expr: "!(ext.method == 'loading' && ext.tier1Only && tier != 'tier1')" },
        {
          set: 'raw',
          expr: "ext.method == 'loading' ? locationsPremium * ext.pct : (ext.method == 'rate_on_groups' ? sum(locations, sumValues(item.sumsInsured, ext.groups)) * (ext.permille / 1000) : (ext.method == 'rate_on_total' ? totalSI * (ext.permille / 1000) : (ext.method == 'rate_on_input' ? pos(risk.extensionInputs[ext.input]) * (ext.permille / 1000) : 0)))",
        },
        { set: 'amount', expr: 'available ? round(raw, dec) : 0' },
        { set: 'referral', expr: "ext.method == 'referral_only'" },
      ],
    },
    { set: 'referralExtension', expr: 'any(extLines, item.referral)' },
    { set: 'extensionsTotal', expr: 'sum(extLines, item.amount)' },
    { set: 'deductibleCode', expr: "uwTerms.deductible || risk.deductible || 'standard'" },
    { set: 'deductibleFactor', expr: "lookup(f.deductible, deductibleCode, 'deductible')" },
    { set: 'technical', expr: '(locationsPremium + extensionsTotal) * deductibleFactor' },
    { set: 'uwLoadingPct', expr: 'num(uwTerms.loadingPct || 0)' },
    { set: 'loaded', expr: 'technical * (1 + uwLoadingPct)' },
    { set: 'requestedDiscount', expr: 'max(0, num(risk.discountPct))' },
    { set: 'discountPct', expr: 'uwTerms.discountPct != null ? num(uwTerms.discountPct) : requestedDiscount' },
    { set: 'discount', expr: 'loaded * discountPct' },
    { set: 'netPremium', expr: 'round(max(charges.minPremium, loaded - discount), dec)' },
    { set: 'policyFee', expr: 'round(charges.policyFee, dec)' },
    { set: 'tax', expr: 'round((netPremium + policyFee) * num(country.vat_rate), dec)' },
  ],
  output: {
    ...base,
    quotable: 'true',
    locations: 'map(locs, {index: item.i, sumInsured: round(item.si, dec), basePremium: round(item.basePremium, dec), factors: item.applied, protection: item.prot, premium: item.premium})',
    'breakdown.locationsPremium': 'round(locationsPremium, dec)',
    'breakdown.extensions': 'map(extLines, item.available ? {code: item.code, amount: item.amount, available: true} : {code: item.code, amount: 0, available: false})',
    'breakdown.extensionsTotal': 'round(extensionsTotal, dec)',
    'breakdown.deductible': 'deductibleCode',
    'breakdown.deductibleFactor': 'deductibleFactor',
    'breakdown.technicalPremium': 'round(technical, dec)',
    'breakdown.uwLoadingPct': 'uwLoadingPct',
    'breakdown.uwLoading': 'round(loaded - technical, dec)',
    'breakdown.discountPct': 'discountPct',
    'breakdown.discount': 'round(discount, dec)',
    'breakdown.minimumPremiumApplied': 'loaded - discount < charges.minPremium',
    'breakdown.premium': 'netPremium',
    'breakdown.policyFee': 'policyFee',
    'breakdown.vatRate': 'num(country.vat_rate)',
    'breakdown.tax': 'tax',
    'breakdown.total': 'round(netPremium + policyFee + tax, dec)',
    'facts.totalSI': 'totalSI',
    'facts.maxLocationSI': 'maxLocationSI',
    'facts.tier': 'tier',
    'facts.hazard': 'occ.hazard',
    'facts.occupancyStatus': 'occ.status',
    'facts.exceedsAutoLimit': 'authority.maxLocationSI != null && maxLocationSI > authority.maxLocationSI',
    'facts.hazardOutsideAuthority': "occ.status == 'refer' || !includes(authority.hazards || ['low'], occ.hazard)",
    'facts.lightConstructionOver1m': `any(locations, item.construction == 'light' && ${SI} > 1000000)`,
    'facts.noCivilDefence': 'any(locations, item.civilDefence == false)',
    'facts.claims3y': 'claims3y',
    'facts.highNatcat': "any(locations, item.natcatZone == 'high')",
    'facts.basementStock': "any(locations, item.floorLevel == 'basement' && pos(item.sumsInsured.STK) > 0)",
    'facts.discountPct': 'requestedDiscount',
    'facts.discountExceedsBand': 'requestedDiscount > (authority.maxDiscount ?? 0)',
    'facts.hasReferralExtension': 'referralExtension',
    'facts.sanctionsHit': '!!sanctionsHit',
    'facts.previouslyDeclined': 'risk.previouslyDeclined == true',
    'facts.accumulationExceeded': `settings.accumulationLimitPerSite != null && any(locations, siteKey(item.address) != '||' && (existingExposure[siteKey(item.address)] || 0) + ${SI} > settings.accumulationLimitPerSite)`,
  },
};
