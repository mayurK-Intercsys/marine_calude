/**
 * Marine Cargo rating model (Marine BRD sections 4 and 9) for the dynamic rating engine.
 * Entries: rate (dispatches to shipment / openCover) and certificate (under an open cover).
 * Step-for-step equivalent of products/marine/rater.js; the parity test proves identical results.
 */

/** Sum insured by Incoterm with uplift and FX, for a shipment variable `s`. */
const sumInsuredSteps = (s) => [
  { set: 'fxRate', expr: `lookup(tables.fx, ${s}.invoice.currency, 'fx')` },
  { set: 'invoice', expr: `num(${s}.invoice.amount)` },
  { set: 'freight', expr: `includes(FREIGHT_EXCLUDED, ${s}.incoterm) ? num(${s}.freight || 0) : 0` },
  { set: 'uplift', expr: `${s}.upliftPct ?? 0.1` },
  { set: 'duty', expr: `num(${s}.duty || 0)` },
  { set: 'siForeign', expr: '(invoice + freight) * (1 + uplift) + duty' },
  { set: 'si', expr: 'round(siForeign * fxRate, dec)' },
  { set: 'calc', expr: `{invoice: invoice, freight: freight, upliftPct: uplift, duty: duty, currency: ${s}.invoice.currency, fxRate: fxRate, siForeign: round(siForeign, 2), siLocal: si}` },
];

/** Route facts: declined country, high-risk route and the higher of the two region factors. */
const routeSteps = (s) => [
  { set: 'origin', expr: `tables.countries[${s}.origin.country] || {region: 'other'}` },
  { set: 'dest', expr: `tables.countries[${s}.destination.country] || {region: 'other'}` },
  { set: 'declinedCountry', expr: "origin.status == 'decline' || dest.status == 'decline'" },
  { set: 'highRiskRoute', expr: "includes(['war_listed', 'refer'], origin.status) || includes(['war_listed', 'refer'], dest.status)" },
  { set: 'regionFactor', expr: 'max(tables.factors.region[origin.region] ?? tables.factors.region.other, tables.factors.region[dest.region] ?? tables.factors.region.other)' },
];

const vesselFactor = "(!context.vessel.found || context.vessel.age == null) ? 1 : band(tables.factors.vesselAge, context.vessel.age, 'factor', 'maxAge', tables.factors.vesselAge[len(tables.factors.vesselAge) - 1].factor)";
const vesselIssue = (s) => `${s}.mode != 'sea' ? false : (!context.vessel.found || context.vessel.age > 25 || context.vessel.iacs == false)`;
const vatFor = (kind) => `(settings.vat[${kind}] || 'standard') == 'zero' ? 0 : num(country.vat_rate)`;

const shipmentBase = {
  valid: 'true', productType: 'risk.productType', tier: 'risk.productType', currency: 'country.currency',
  sumInsured: 'si', maxLocationSI: 'si', sumInsuredCalc: 'calc', period: 'period',
};

const shipment = {
  steps: [
    { set: 'dec', expr: 'country.currency_decimals' },
    { set: 'commodity', expr: 'find(tables.commodities, item.code == risk.commodity)' },
    { error: 'COMMODITY_UNKNOWN', when: 'commodity == null' },
    { error: 'INLAND_MODE_INVALID', when: "risk.productType == 'inland' && (risk.war || risk.mode == 'sea' || risk.mode == 'air')" },
    { set: 'byMode', expr: "risk.productType == 'inland' ? ['ITC-A', 'ITC-B'] : (risk.mode == 'air' ? ['ICC-AIR'] : ['ICC-A', 'ICC-B', 'ICC-C'])" },
    { error: 'CLAUSE_NOT_ALLOWED', when: 'commodity != null && !commodity.prohibited && !includes(filter(byMode, commodity.rates[item] != null), risk.clause)', field: "'clause'" },
    { error: 'INVOICE_VALUE_REQUIRED', when: '!(num(risk.invoice.amount) > 0)' },
    { checkpoint: true },
    ...sumInsuredSteps('risk'),
    ...routeSteps('risk'),
    { set: 'period', expr: '{inception: risk.sailingDate, expiry: addDays(risk.sailingDate, settings.transitValidityDays || 90)}' },
    { when: 'commodity.prohibited', return: { ...shipmentBase, quotable: 'false', notQuotableReason: "'COMMODITY_PROHIBITED'" } },
    { when: 'declinedCountry', return: { ...shipmentBase, quotable: 'false', notQuotableReason: "'COUNTRY_DECLINED'" } },
    { when: 'si > settings.maxOnlineSI', return: { ...shipmentBase, quotable: 'false', notQuotableReason: "'ABOVE_ONLINE_LIMIT'" } },
    { set: 'f', expr: 'tables.factors' },
    { set: 'factorsApplied', expr: `{mode: f.mode[risk.mode], region: regionFactor, packing: f.packing[risk.packing] ?? 1, container: f.container[risk.container] ?? 1, vessel: risk.mode == 'sea' ? (${vesselFactor}) : 1}` },
    { set: 'kind', expr: "risk.productType == 'inland' ? 'domestic' : risk.direction" },
    { set: 'vatRate', expr: vatFor('kind') },
    { set: 'rate', expr: 'commodity.rates[risk.clause]' },
    { set: 'base', expr: 'si * rate * (factorsApplied.mode * factorsApplied.region * factorsApplied.packing * factorsApplied.container * factorsApplied.vessel)' },
    { set: 'war', expr: 'risk.war && f.war[risk.mode] ? si * f.war[risk.mode] : 0' },
    { set: 'srcc', expr: 'risk.srcc ? si * f.srcc : 0' },
    {
      each: 'risk.extensions || []', as: 'code', collect: 'extLines', steps: [
        { set: 'ext', expr: 'tables.extensions[code]' },
        { set: 'present', expr: '!!ext' },
        { set: 'amount', expr: "round(ext.method == 'rate_on_si' ? si * ext.rate : (ext.method == 'loading' ? base * ext.pct : 0), dec)" },
        { set: 'referral', expr: "ext.method == 'referral_only'" },
      ],
    },
    { set: 'extensions', expr: 'map(filter(extLines, item.present), {code: item.code, amount: item.amount})' },
    { set: 'extTotal', expr: 'sum(extensions, item.amount)' },
    { set: 'technical', expr: 'base + war + srcc + extTotal' },
    { set: 'uwLoadingPct', expr: 'num(uwTerms.loadingPct || 0)' },
    { set: 'loaded', expr: 'technical * (1 + uwLoadingPct)' },
    { set: 'discountIn', expr: 'num(risk.discountPct || 0)' },
    { set: 'dPct', expr: 'uwTerms.discountPct != null ? num(uwTerms.discountPct) : discountIn' },
    { set: 'discount', expr: 'loaded * dPct' },
    { set: 'minPremium', expr: 'tables.charges.minPremium' },
    { set: 'premium', expr: 'round(max(minPremium, loaded - discount), dec)' },
    { set: 'fee', expr: 'round(tables.charges.policyFee, dec)' },
    { set: 'tax', expr: 'round((premium + fee) * vatRate, dec)' },
    { set: 'ded', expr: 'tables.deductibles[commodity.group] || tables.deductibles.general' },
    { set: 'asOf', expr: 'context.asOf || today()' },
  ],
  output: {
    ...shipmentBase,
    quotable: 'true',
    commodityGroup: 'commodity.group',
    'breakdown.basePremium': 'round(base, dec)',
    'breakdown.warPremium': 'round(war, dec)',
    'breakdown.srccPremium': 'round(srcc, dec)',
    'breakdown.extensions': 'extensions',
    'breakdown.extensionsTotal': 'round(extTotal, dec)',
    'breakdown.technicalPremium': 'round(technical, dec)',
    'breakdown.uwLoadingPct': 'uwLoadingPct',
    'breakdown.uwLoading': 'round(loaded - technical, dec)',
    'breakdown.discountPct': 'dPct',
    'breakdown.discount': 'round(discount, dec)',
    'breakdown.minimumPremiumApplied': 'loaded - discount < minPremium',
    'breakdown.premium': 'premium',
    'breakdown.policyFee': 'fee',
    'breakdown.vatRate': 'vatRate',
    'breakdown.tax': 'tax',
    'breakdown.total': 'round(premium + fee + tax, dec)',
    'breakdown.locationsPremium': 'round(base, dec)',
    'breakdown.deductible': '{pct: ded.pct, min: ded.min, amount: round(max(ded.min, si * ded.pct), dec)}',
    'breakdown.factors': 'factorsApplied',
    'breakdown.rate': 'rate',
    'facts.sumInsured': 'si',
    'facts.exceedsAutoLimit': 'authority.maxSI != null && si > authority.maxSI',
    'facts.referralCommodity': '!!(commodity.referral || (commodity.referralAboveSI && si > commodity.referralAboveSI))',
    'facts.highRiskRoute': 'highRiskRoute',
    'facts.vesselIssue': vesselIssue('risk'),
    'facts.vesselAge': 'context.vessel.age ?? null',
    'facts.unpackedAllRisks': "includes(PACKED_EXEMPT, risk.packing) && includes(['ICC-A', 'ICC-AIR', 'ITC-A'], risk.clause)",
    'facts.departureSoon': 'daysInclusive(asOf, risk.sailingDate) <= 1',
    'facts.sanctionsHit': '!!sanctionsHit',
    'facts.discountPct': 'discountIn',
    'facts.discountExceedsBand': 'discountIn > (authority.maxDiscount ?? 0)',
    'facts.hasReferralExtension': 'any(filter(extLines, item.present), item.referral)',
    'facts.previouslyDeclined': 'risk.previouslyDeclined == true',
  },
};

const ocBase = {
  valid: 'true', productType: "'open_cover'", tier: "'open_cover'", currency: 'country.currency', sumInsured: 'round(turnover, dec)',
  maxLocationSI: 'num(risk.perSendingLimit)', period: '{inception: inception, expiry: annualExpiry(inception)}',
};

const openCover = {
  steps: [
    { set: 'dec', expr: 'country.currency_decimals' },
    { set: 'lines', expr: 'risk.commodities || []' },
    { set: 'share', expr: 'sum(lines, num(item.share || 0))' },
    { error: 'COMMODITY_SCHEDULE_REQUIRED', when: 'len(lines) == 0' },
    { error: 'SHARES_MUST_TOTAL_100', when: 'abs(share - 1) > 0.001' },
    {
      each: 'lines', as: 'l', index: 'i', collect: 'resolved', steps: [
        { set: 'commodity', expr: 'find(tables.commodities, item.code == l.commodity)' },
        { error: 'COMMODITY_UNKNOWN', when: 'commodity == null', field: "'commodities.' + i" },
        { error: 'CLAUSE_NOT_ALLOWED', when: 'commodity != null && commodity.rates[l.clause] == null', field: "'commodities.' + i" },
      ],
    },
    { checkpoint: true },
    { set: 'turnover', expr: 'num(risk.estimatedTurnover)' },
    { set: 'inception', expr: 'risk.inceptionDate || today()' },
    { when: "channel == 'b2c'", return: { ...ocBase, quotable: 'false', notQuotableReason: "'OPEN_COVER_VIA_BROKER'" } },
    { when: 'any(resolved, item.commodity.prohibited)', return: { ...ocBase, quotable: 'false', notQuotableReason: "'COMMODITY_PROHIBITED'" } },
    { set: 'f', expr: 'tables.factors' },
    { set: 'regions', expr: "len(risk.regions) ? risk.regions : ['other']" },
    { set: 'regionFactor', expr: 'max_of(regions, f.region[item] ?? f.region.other)' },
    { set: 'loading', expr: '1 + num(uwTerms.loadingPct || 0)' },
    { set: 'discountPct', expr: 'uwTerms.discountPct != null ? num(uwTerms.discountPct) : num(risk.discountPct || 0)' },
    { set: 'adjust', expr: 'loading * (1 - discountPct)' },
    { set: 'agreedRates', expr: 'map(resolved, {commodity: item.commodity.code, clause: item.l.clause, share: num(item.l.share), rate: fixed(item.commodity.rates[item.l.clause] * regionFactor * adjust, 6), group: item.commodity.group})' },
    { set: 'weighted', expr: 'sum(agreedRates, item.rate * item.share)' },
    { set: 'warRate', expr: 'risk.war ? f.war.sea * adjust : 0' },
    { set: 'srccRate', expr: 'risk.srcc ? f.srcc * adjust : 0' },
    { set: 'estimatedPremium', expr: 'round(turnover * (weighted + warRate + srccRate), dec)' },
    { set: 'depositPct', expr: 'risk.depositPct ?? settings.depositPct' },
    { set: 'deposit', expr: "risk.premiumBasis == 'deposit' ? round(estimatedPremium * depositPct, dec) : 0" },
    { set: 'fee', expr: 'round(tables.charges.openCoverFee, dec)' },
    { set: 'vatRate', expr: vatFor("'open_cover'") },
    { set: 'tax', expr: 'round((deposit + fee) * vatRate, dec)' },
  ],
  output: {
    ...ocBase,
    quotable: 'true',
    agreedRates: 'agreedRates',
    agreedWarRate: 'fixed(warRate, 6)',
    agreedSrccRate: 'fixed(srccRate, 6)',
    'breakdown.weightedRate': 'fixed(weighted, 6)',
    'breakdown.estimatedPremium': 'estimatedPremium',
    'breakdown.depositPct': "risk.premiumBasis == 'deposit' ? depositPct : 0",
    'breakdown.uwLoadingPct': 'num(uwTerms.loadingPct || 0)',
    'breakdown.discountPct': 'discountPct',
    'breakdown.uwLoading': '0',
    'breakdown.discount': '0',
    'breakdown.minimumPremiumApplied': 'false',
    'breakdown.locationsPremium': 'estimatedPremium',
    'breakdown.extensionsTotal': '0',
    'breakdown.premium': 'deposit',
    'breakdown.policyFee': 'fee',
    'breakdown.vatRate': 'vatRate',
    'breakdown.tax': 'tax',
    'breakdown.total': 'round(deposit + fee + tax, dec)',
    'facts.sumInsured': 'turnover',
    'facts.openCoverNeedsApproval': '!authority.canBindOpenCover || turnover > (authority.maxOpenCoverTurnover ?? 0)',
    'facts.referralCommodity': 'any(resolved, item.commodity.referral)',
    'facts.highRiskRoute': 'false',
    'facts.discountPct': 'num(risk.discountPct || 0)',
    'facts.discountExceedsBand': 'num(risk.discountPct || 0) > (authority.maxDiscount ?? 0)',
    'facts.sanctionsHit': '!!sanctionsHit',
    'facts.previouslyDeclined': 'risk.previouslyDeclined == true',
  },
};

const certificate = {
  steps: [
    { set: 'dec', expr: 'country.currency_decimals' },
    { set: 'terms', expr: 'policy.risk_data' },
    { set: 'agreed', expr: 'find(policy.rating.agreedRates, item.commodity == shipment.commodity)' },
    { set: 'commodity', expr: 'find(tables.commodities, item.code == shipment.commodity)' },
    { when: 'commodity == null', return: { valid: 'false', errors: "[{code: 'COMMODITY_UNKNOWN'}]" } },
    { when: '!(num(shipment.invoice.amount) > 0)', return: { valid: 'false', errors: "[{code: 'INVOICE_VALUE_REQUIRED'}]" } },
    ...sumInsuredSteps('shipment'),
    ...routeSteps('shipment'),
    { when: 'commodity.prohibited', return: { valid: 'true', quotable: 'false', notQuotableReason: "'COMMODITY_PROHIBITED'", sumInsured: 'si' } },
    { when: 'declinedCountry', return: { valid: 'true', quotable: 'false', notQuotableReason: "'COUNTRY_DECLINED'", sumInsured: 'si' } },
    { set: 'clause', expr: 'agreed.clause || shipment.clause' },
    { set: 'rateValue', expr: 'agreed != null ? agreed.rate : (commodity.rates[clause] ?? 0)' },
    { set: 'vesselF', expr: `shipment.mode == 'sea' ? (${vesselFactor}) : 1` },
    { set: 'base', expr: 'si * rateValue * vesselF' },
    { set: 'war', expr: "terms.war && includes(['sea', 'air'], shipment.mode) ? si * policy.rating.agreedWarRate : 0" },
    { set: 'srcc', expr: 'terms.srcc ? si * policy.rating.agreedSrccRate : 0' },
    { set: 'loaded', expr: '(base + war + srcc) * (1 + num(uwTerms.loadingPct || 0))' },
    { set: 'premium', expr: 'round(max(tables.charges.minCertificatePremium, loaded), dec)' },
    { set: 'kind', expr: "shipment.productType == 'inland' ? 'domestic' : shipment.direction" },
    { set: 'vatRate', expr: vatFor('kind') },
    { set: 'tax', expr: 'round(premium * vatRate, dec)' },
    { set: 'ded', expr: 'tables.deductibles[commodity.group] || tables.deductibles.general' },
    { set: 'asOf', expr: 'context.asOf || today()' },
  ],
  output: {
    valid: 'true', quotable: 'true', sumInsured: 'si', sumInsuredCalc: 'calc', clause: 'clause',
    'breakdown.rate': 'rateValue',
    'breakdown.vesselFactor': 'vesselF',
    'breakdown.basePremium': 'round(base, dec)',
    'breakdown.warPremium': 'round(war, dec)',
    'breakdown.srccPremium': 'round(srcc, dec)',
    'breakdown.uwLoadingPct': 'num(uwTerms.loadingPct || 0)',
    'breakdown.premium': 'premium',
    'breakdown.vatRate': 'vatRate',
    'breakdown.tax': 'tax',
    'breakdown.total': 'round(premium + tax, dec)',
    'breakdown.deductible': '{pct: ded.pct, min: ded.min, amount: round(max(ded.min, si * ded.pct), dec)}',
    'facts.sumInsured': 'si',
    'facts.outsideTerms': "agreed == null || (shipment.clause && shipment.clause != agreed.clause) || (terms.interest != 'all' && terms.interest != (shipment.productType == 'inland' ? 'inland' : shipment.direction))",
    'facts.exceedsSendingLimit': 'si > num(terms.perSendingLimit)',
    'facts.turnoverExceeded': 'turnoverUsed + si > num(terms.estimatedTurnover)',
    'facts.highRiskRoute': 'highRiskRoute',
    'facts.vesselIssue': vesselIssue('shipment'),
    'facts.vesselAge': 'context.vessel.age ?? null',
    'facts.departureSoon': 'daysInclusive(asOf, shipment.sailingDate) <= 1',
    'facts.sanctionsHit': '!!sanctionsHit',
  },
};

module.exports = {
  name: 'Marine Cargo',
  requiredTables: ['commodities', 'countries', 'factors', 'extensions', 'deductibles', 'fx', 'charges'],
  constants: { FREIGHT_EXCLUDED: ['EXW', 'FCA', 'FOB'], PACKED_EXEMPT: ['bulk', 'unpacked'] },
  prepare: [{ as: 'vessel', provider: 'vessel', when: "risk.productType != 'open_cover' && risk.mode == 'sea'", arg: 'risk.vessel || {}' }],
  entries: {
    rate: { steps: [{ call: 'openCover', when: "risk.productType == 'open_cover'" }, { call: 'shipment' }] },
    shipment,
    openCover,
    certificate,
  },
};
